"""Build the PostPrep icon CSS and WOFF2 subsets with fontTools and Brotli."""

import re
import subprocess
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont


ROOT = Path(__file__).resolve().parents[1]
VENDOR = ROOT / "assets/vendor/fontawesome"
NAMES = re.compile(r"\bfa-[a-z0-9-]+\b")
FILES = subprocess.check_output(["git", "ls-files", "-z", "*.html", "assets/*.js"], cwd=ROOT)
used = set()
for name in FILES.decode().split("\0"):
    if name and not name.startswith(("assets/vendor/", "assets/rvc-engine/")):
        used.update(NAMES.findall((ROOT / name).read_text(encoding="utf-8")))
page_icons = (ROOT / "assets/v3/src/85-pages-rich.css").read_text(encoding="utf-8")
page_codes = {int(code, 16) for code in re.findall(r"\\([0-9a-f]+)", page_icons)}

source = (VENDOR / "css/all.min.css").read_text(encoding="utf-8")
license_header = source.split("*/", 1)[0] + "*/"
glyphs = {
    name: int(code, 16)
    for selectors, code in re.findall(r'([^{}]+)\{--fa:"\\([0-9a-f]+)"\}', source)
    for name in NAMES.findall(selectors)
    if name in used
}
utilities = {"fa-brands", "fa-regular", "fa-solid", "fa-spin"}
if missing := used - glyphs.keys() - utilities:
    raise SystemExit(f"Unmapped icon classes: {', '.join(sorted(missing))}")

css = [license_header, "/* Generated by tools/build-icon-subset.py. */"]
base = ".fa,.fa-brands,.fa-regular,.fa-solid,.fab,.far,.fas"
css.extend([
    f"{base}{{display:var(--fa-display,inline-block);font-style:normal;font-variant:normal;"
    "line-height:1;text-rendering:auto;-webkit-font-smoothing:antialiased;-moz-osx-font-smoothing:grayscale}",
    ",".join(f"{selector}::before" for selector in base.split(",")) + "{content:var(--fa)}",
    '.fa,.fa-regular,.fa-solid,.far,.fas{font-family:"Font Awesome 6 Free"}',
    '.fa-brands,.fab{font-family:"Font Awesome 6 Brands";font-weight:400}',
    ".fa,.fa-solid,.fas{font-weight:900}",
    ".fa-regular,.far{font-weight:400}",
    ".fa-spin{animation:postprep-icon-spin 2s linear infinite}",
    "@keyframes postprep-icon-spin{to{transform:rotate(360deg)}}",
    "@media(prefers-reduced-motion:reduce){.fa-spin{animation:none}}",
])
for variant, weight, family, names in (
    ("solid", 900, "Font Awesome 6 Free", used - {"fa-github", "fa-qq"}),
    ("regular", 400, "Font Awesome 6 Free", {"fa-circle", "fa-copy"}),
    ("brands", 400, "Font Awesome 6 Brands", {"fa-github", "fa-qq"}),
):
    font = TTFont(VENDOR / f"webfonts/fa-{variant}-{weight}.woff2", recalcTimestamp=False)
    codes = {glyphs[name] for name in names & glyphs.keys()}
    if variant == "solid":
        codes.update(page_codes)
    if missing := codes - font.getBestCmap().keys():
        raise SystemExit(f"Missing {variant} glyphs: {sorted(missing)}")
    options = subset.Options()
    options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]
    options.name_legacy = True
    options.name_languages = ["*"]
    builder = subset.Subsetter(options=options)
    builder.populate(unicodes=codes)
    builder.subset(font)
    output = f"postprep-{variant}.woff2"
    font.save(VENDOR / "webfonts" / output)
    css.append(f'@font-face{{font-family:"{family}";font-weight:{weight};font-display:block;'
               f'src:url(../webfonts/{output}) format("woff2")}}')
css.extend(f'.{name}{{--fa:"\\{code:x}"}}' for name, code in sorted(glyphs.items()))
(VENDOR / "css/postprep-icons.css").write_text("\n".join(css) + "\n", encoding="utf-8", newline="\n")
